export const LEVEL_100_SCALING_CONSTANT = 9.204065;
export const UNIQUE_SINGLE_TOWER_MULTIPLIER = 4 / 0.9; // 4.4444x
export const DIVINE_SINGLE_TOWER_MULTIPLIER = 1.2 / 0.9; // 1.3333x

function estimateDmgLv1(baseDpsLv100: number, spa: number): number {
  return Math.round((baseDpsLv100 * spa) / LEVEL_100_SCALING_CONSTANT);
}

export interface PlacementCapMath {
  cap: number;
  uniqueMultiplier: number;
  divineTeamMultiplier: number;
  netGainVsUnenchantedPercent: number;
  netGainVsDivinePercent: number;
  verdict: "mandatory_unique" | "strong_unique" | "efficient_unique" | "prefer_divine_ceiling";
  headline: string;
  explanation: string;
}

export function getUniquePlacementMath(cap: number): PlacementCapMath {
  const safeCap = Math.max(1, cap);
  const uniqueMult = UNIQUE_SINGLE_TOWER_MULTIPLIER;
  const divineTeamMult = DIVINE_SINGLE_TOWER_MULTIPLIER * safeCap;
  const vsBase = ((uniqueMult - safeCap) / safeCap) * 100;
  const vsDivine = ((uniqueMult - divineTeamMult) / divineTeamMult) * 100;

  if (safeCap === 1) {
    return {
      cap: safeCap,
      uniqueMultiplier: uniqueMult,
      divineTeamMultiplier: divineTeamMult,
      netGainVsUnenchantedPercent: Number(vsBase.toFixed(1)),
      netGainVsDivinePercent: Number(vsDivine.toFixed(1)),
      verdict: "mandatory_unique",
      headline: `1-Cap идеал: +${vsBase.toFixed(1)}% чистого DPS без потери слотов`,
      explanation:
        "При базовом лимите 1 башня трейт Unique ничего не отбирает: даёт +344.4% чистого урона к базе и на +233.3% обходит Divine.",
    };
  }

  if (safeCap === 2) {
    return {
      cap: safeCap,
      uniqueMultiplier: uniqueMult,
      divineTeamMultiplier: divineTeamMult,
      netGainVsUnenchantedPercent: Number(vsBase.toFixed(1)),
      netGainVsDivinePercent: Number(vsDivine.toFixed(1)),
      verdict: "strong_unique",
      headline: `2-Cap буст: +${vsBase.toFixed(1)}% к паре без трейта (+${vsDivine.toFixed(1)}% к 2× Divine)`,
      explanation:
        "1 башня с Unique (4.444x) уверенно обгоняет 2 башни с Divine (2.667x) на +66.7% и стоит вдвое дешевле в иенах.",
    };
  }

  if (safeCap === 3) {
    return {
      cap: safeCap,
      uniqueMultiplier: uniqueMult,
      divineTeamMultiplier: divineTeamMult,
      netGainVsUnenchantedPercent: Number(vsBase.toFixed(1)),
      netGainVsDivinePercent: Number(vsDivine.toFixed(1)),
      verdict: "efficient_unique",
      headline: `3-Cap баланс: +${vsBase.toFixed(1)}% к 3 копиям (+${vsDivine.toFixed(1)}% к 3× Divine)`,
      explanation:
        "1× Unique (4.444x) обходит 3× Divine (4.0x) на +11.1% и экономит 3× стоимость прокачки в ¥, оставаясь оптимумом по DPS/иена.",
    };
  }

  return {
    cap: safeCap,
    uniqueMultiplier: uniqueMult,
    divineTeamMultiplier: divineTeamMult,
    netGainVsUnenchantedPercent: Number(vsBase.toFixed(1)),
    netGainVsDivinePercent: Number(vsDivine.toFixed(1)),
    verdict: "prefer_divine_ceiling",
    headline: `${safeCap}-Cap парадокс: ${safeCap}× Divine (${divineTeamMult.toFixed(2)}x) выше 1× Unique (4.44x)`,
    explanation: `В длинном Infinite ${safeCap} копии с Divine (${divineTeamMult.toFixed(2)}x) бьют 1 башню с Unique (4.444x) по потолку урона; Unique выигрывает только дешевизной прокачки 1 слота в коротких Story-актах.`,
  };
}

