-- 1. Таблица персонажей (синхронизируется из Google Таблицы)
create table if not exists public.units (
  slug text primary key,
  name text not null,
  game_name text not null,
  anime_name text not null,
  is_shiny boolean not null default false,
  value integer null,
  value_display text not null default 'N/A',
  demand numeric(4, 2) not null default 0,
  trend text not null default 'Stable',
  raw_trend text not null default 'Stable',
  tier text not null,
  sub_tier text not null,
  information text not null default '',
  source_tab text not null default '',
  rank integer not null default 0,
  updated_at timestamptz not null default now()
);

create index if not exists idx_units_tier on public.units (tier);
create index if not exists idx_units_trend on public.units (trend);
create index if not exists idx_units_value on public.units (value desc nulls first);
create index if not exists idx_units_demand on public.units (demand desc);

-- 2. История изменения цены и спроса (для графиков Recharts)
create table if not exists public.unit_price_history (
  id bigint generated by default as identity primary key,
  unit_slug text not null references public.units (slug) on delete cascade,
  recorded_at date not null default current_date,
  value integer not null,
  demand numeric(4, 2) not null,
  trend text not null default 'Stable',
  created_at timestamptz not null default now(),
  unique (unit_slug, recorded_at)
);

create index if not exists idx_price_history_slug_date
  on public.unit_price_history (unit_slug, recorded_at asc);

-- 3. Кэш AI-разборов от Gemini
create table if not exists public.unit_ai_analyses (
  unit_slug text primary key references public.units (slug) on delete cascade,
  why_this_price text not null,
  current_meta text not null,
  growth_forecast text not null,
  verdict text not null,
  verdict_label text not null,
  confidence integer not null default 75,
  key_drivers jsonb not null default '[]'::jsonb,
  model text null,
  generated_at timestamptz not null default now()
);

-- 4. Метаданные последней синхронизации
create table if not exists public.market_metadata (
  key text primary key,
  value text not null,
  updated_at timestamptz not null default now()
);

-- 5. Row Level Security (RLS): публичное чтение, запись только через service_role
alter table public.units enable row level security;
alter table public.unit_price_history enable row level security;
alter table public.unit_ai_analyses enable row level security;
alter table public.market_metadata enable row level security;

drop policy if exists "Public read units" on public.units;
create policy "Public read units"
  on public.units for select
  using (true);

drop policy if exists "Public read price history" on public.unit_price_history;
create policy "Public read price history"
  on public.unit_price_history for select
  using (true);

drop policy if exists "Public read ai analyses" on public.unit_ai_analyses;
create policy "Public read ai analyses"
  on public.unit_ai_analyses for select
  using (true);

drop policy if exists "Public read market metadata" on public.market_metadata;
create policy "Public read market metadata"
  on public.market_metadata for select
  using (true);
